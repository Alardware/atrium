  const DICOS = { fr: FR, en: EN };

  function langueParDefaut() {
    try {
      const enregistree = localStorage.getItem('atrium.lang');
      if (enregistree && DICOS[enregistree]) return enregistree;
    } catch (e) {}
    const n = (navigator.language || 'fr').slice(0, 2).toLowerCase();
    return DICOS[n] ? n : 'en';
  }

  let LANG = langueParDefaut();

  function t(cle, vars) {
    let s = (DICOS[LANG] && DICOS[LANG][cle]) || FR[cle] || cle;
    if (vars) Object.keys(vars).forEach((k) => { s = s.split('{' + k + '}').join(vars[k]); });
    return s;
  }

  function appliquer(racine) {
    (racine || document).querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    (racine || document).querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.placeholder = t(el.getAttribute('data-i18n-ph'));
    });
    (racine || document).querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.title = t(el.getAttribute('data-i18n-title'));
    });
    document.documentElement.lang = LANG;
  }

  window.i18n = {
    t,
    appliquer,
    get langue() { return LANG; },
    set langue(v) {
      if (!DICOS[v]) return;
      LANG = v;
      try { localStorage.setItem('atrium.lang', v); } catch (e) {}
      appliquer();
    },
    langues: Object.keys(DICOS),
  };
  window.t = t;
